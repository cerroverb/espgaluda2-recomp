#!/usr/bin/env python3
"""Writes src/renut_engine/futari_renut_hooks.h: Renut's renderer hooked into Espgaluda II's Direct3D by name.

Adapted from futari-nx's tools/renut_futari_hooks.py (github.com/ChanseyIsTheBest/futari-nx, pull request 2, commit
7f5a36a), GPL-3.0 (LICENSE-GPL-3.0): its read_map, the renderer's hook-name scan, the owned-address scan and the
header writer, unchanged in what they emit. Left out: the rewriting of N&B hook lines (the renderer's lines are
already by name) and everything for game cores (Espgaluda II's dat*.xex link no Direct3D, see WORKLOG.md), so the
cores' entry table is empty.

The map is src/renut_engine/espgaluda2_d3d_functions.txt: `<name> <default.xex address> <how it was confirmed>`.
An address one of this project's own hooks defines (outside src/renut_engine, e.g. src/latency_patch.cpp's Swap)
is left to that hook, which must hand over with FUTARI_RENUT_YIELD(name) (src/renut_engine/futari_renut_yield.h).

  python3 tools/renut_hooks.py [--check]
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src')
ENGINE = os.path.join(SRC, 'renut_engine')
GPU = os.path.join(ENGINE, 'gpu')
MAP = os.path.join(ENGINE, 'espgaluda2_d3d_functions.txt')
OUT_H = os.path.join(ENGINE, 'futari_renut_hooks.h')

NEW_HOOK = re.compile(r'^\s*FUTARI_RENUT_HOOK\((\w+), .+?\);')
NEW_RAW = re.compile(r'^\s*FUTARI_RENUT_HOOK_RAW\((\w+)\)')


def read_map():
    out = {}
    for line in open(MAP, encoding='utf-8'):
        f = line.split('#')[0].split()
        if len(f) >= 2:
            name, addr = f[0], int(f[1], 16)
            if name in out:
                sys.exit('espgaluda2_d3d_functions.txt: %s twice' % name)
            out[name] = addr
    addrs = {}
    for n, a in out.items():
        if a in addrs:
            sys.exit('espgaluda2_d3d_functions.txt: %08X is both %s and %s' % (a, addrs[a], n))
        addrs[a] = n
    return out


def hook_names():
    names = {}
    paths = []
    for ext in ('*.cpp', '*.h'):
        paths += glob.glob(os.path.join(GPU, '**', ext), recursive=True)
    for path in sorted(p for p in paths if os.path.basename(p) != 'banjo_renut_select.h'):
        for line in open(path, encoding='utf-8'):
            m = NEW_HOOK.match(line) or NEW_RAW.match(line)
            if m:
                names.setdefault(m.group(1), []).append(os.path.relpath(path, GPU))
    return names


def strip_comments(text):
    return re.sub(r'//[^\n]*|/\*.*?\*/', '', text, flags=re.S)


def owned_default():
    """default.xex addresses this project's own hooks define (outside the renderer): {address: file}."""
    owned = {}
    for d, _, fs in os.walk(SRC):
        if os.path.abspath(d).startswith(os.path.abspath(ENGINE)):
            continue
        for f in fs:
            if not f.endswith(('.cpp', '.h')):
                continue
            path = os.path.join(d, f)
            text = strip_comments(open(path, encoding='utf-8', errors='ignore').read())
            for m in re.finditer(r'\b(?:REX_HOOK_RAW|REX_HOOK|REX_STUB)\(\s*sub_(82[0-9A-Fa-f]{6})\b', text):
                owned[int(m.group(1), 16)] = os.path.relpath(path, ROOT)
            for m in re.finditer(r'extern\s+"C"\s+REX_FUNC\(\s*sub_(82[0-9A-Fa-f]{6})\)\s*\{', text):
                owned[int(m.group(1), 16)] = os.path.relpath(path, ROOT)
    return owned


HEADER = '''// Generated by tools/renut_hooks.py from src/renut_engine/espgaluda2_d3d_functions.txt: do not edit.
// Renut's renderer (src/renut_engine/gpu: futari-nx's copy of banjo-nx's adaptation of github.com/masterspike52/reNut
// by reNut and masterspike52) hooked into Espgaluda II's Direct3D by name (banjo_renut_select.h: FUTARI_RENUT_HOOK).
// Format and macros as futari-nx's tools/renut_futari_hooks.py writes them (GPL-3.0).
#pragma once

#include <cstdint>

#include <rex/hook.h>
#include <rex/ppc.h>
'''


def write_header(names, mapping, owned):
    out = [HEADER]
    out.append('// Every hook\'s entry (defined by its FUTARI_RENUT_HOOK in the renderer).')
    for n in sorted(names):
        out.append('extern "C" void futari_renut_entry_%s(PPCContext& ctx, uint8_t* base);' % n)
    out.append('')
    out.append('// default.xex\'s hook sites: the game\'s function runs Renut\'s side while Renut\'s renderer is chosen.')
    for n in sorted(names):
        a = mapping.get(n)
        if a is None:
            out.append('#define FUTARI_RENUT_SITE_%s  // not in Espgaluda II\'s Direct3D (or not confirmed)' % n)
        elif a in owned:
            out.append('#define FUTARI_RENUT_SITE_%s  // sub_%08X: this project\'s own hook (%s) yields' % (n, a, owned[a]))
        else:
            out.append('#define FUTARI_RENUT_SITE_%s \\' % n)
            out.append('  REX_EXTERN(__imp__sub_%08X); \\' % a)
            out.append('  extern "C" REX_FUNC(sub_%08X) { \\' % a)
            out.append('    if (::banjo::renut_gpu::Active()) { futari_renut_entry_%s(ctx, base); return; } \\' % n)
            out.append('    __imp__sub_%08X(ctx, base); \\' % a)
            out.append('  }')
    out.append('')
    out.append('// No game cores link Direct3D in Espgaluda II: the cores\' forwarding table is empty.')
    out.append('#define FUTARI_RENUT_CORE_ENTRIES(X)')
    out.append('#define FUTARI_RENUT_CORE_COUNT 0')
    out.append('')
    return '\n'.join(out)


def main():
    check = '--check' in sys.argv
    mapping = read_map()
    names = hook_names()
    owned = owned_default()
    unknown = sorted(set(mapping) - set(names))
    if unknown:
        sys.exit('espgaluda2_d3d_functions.txt names functions no hook has: ' + ', '.join(unknown))
    problems = []
    for n, a in mapping.items():
        if a in owned:
            text = open(os.path.join(ROOT, owned[a]), encoding='utf-8').read()
            if 'FUTARI_RENUT_YIELD(%s)' % n not in text:
                problems.append('%s hooks sub_%08X (%s) without FUTARI_RENUT_YIELD(%s)' % (owned[a], a, n, n))
    if problems:
        sys.exit('\n'.join(problems))
    text = write_header(names, mapping, owned)
    old = open(OUT_H, encoding='utf-8').read() if os.path.exists(OUT_H) else ''
    if check:
        sys.exit(0 if old == text else 'futari_renut_hooks.h is out of date: run tools/renut_hooks.py')
    if old != text:
        open(OUT_H, 'w', encoding='utf-8').write(text)
    print('%d hooks, %d mapped (%d yield to this project\'s hooks)' % (
        len(names), len(mapping), sum(1 for a in mapping.values() if a in owned)))


if __name__ == '__main__':
    main()
